    protected function setUp():void
    {
        parent::setUp();
        if(getenv('RUN_PGSQL_BOOLEAN_TESTS')!=='1')$this->markTestSkipped('Explicit opt-in required for rollback-only PostgreSQL tests.');
        try {
            config(['database.default'=>'pgsql','session.driver'=>'array','cache.default'=>'array','app.debug'=>false]);DB::purge('pgsql');
            $this->pg=DB::connection('pgsql');$this->assertInstanceOf(PostgresBooleanConnection::class,$this->pg);
            $this->pg->beginTransaction();
            $this->pg->statement("SET LOCAL statement_timeout = '15s'");$this->pg->statement("SET LOCAL lock_timeout = '2s'");
            $this->pg->statement('CREATE TEMP TABLE boolean_binding_probe (id bigint GENERATED BY DEFAULT AS IDENTITY, is_active boolean NOT NULL) ON COMMIT DROP');
        }catch(\Throwable $e){if($this->pg && $this->pg->transactionLevel())$this->pg->rollBack();$this->fail('PostgreSQL test setup failed; details redacted ('.get_class($e).', code '.$e->getCode().').');}
    }
    protected function tearDown():void
    {
        if($this->pg){
            while($this->pg->transactionLevel()>0)$this->pg->rollBack();
            $this->assertNull($this->pg->selectOne("select to_regclass('pg_temp.boolean_binding_probe') as remaining")->remaining);
            DB::disconnect('pgsql');
        }
        parent::tearDown();
    }
    private function expectedState(callable $operation,string $state):void
    {
        $this->pg->statement('SAVEPOINT expected_legacy_error');
        try {$operation();$this->fail('Expected PostgreSQL integer/Boolean rejection.');}
        catch(QueryException $e){$this->assertSame($state,(string)$e->getCode());}
        finally {$this->pg->statement('ROLLBACK TO SAVEPOINT expected_legacy_error');$this->pg->statement('RELEASE SAVEPOINT expected_legacy_error');}
    }
    public function test_live_integer_rejection_and_boolean_crud_with_emulated_and_native_parameters():void
    {
        $pdo=$this->pg->getPdo();$mode=$pdo->getAttribute(\PDO::ATTR_EMULATE_PREPARES);$disable=null;
        if(defined('PDO::PGSQL_ATTR_DISABLE_PREPARES'))$disable=$pdo->getAttribute(\PDO::PGSQL_ATTR_DISABLE_PREPARES);
        try {
            $pdo->setAttribute(\PDO::ATTR_EMULATE_PREPARES,true);
            $stock=new PostgresConnection($pdo);
            foreach([true,false] as $flag){
                $this->expectedState(fn()=>$stock->selectOne('SELECT TRUE = ? AS same',[$flag]),'42883');
                $this->expectedState(fn()=>$stock->insert('INSERT INTO pg_temp.boolean_binding_probe (is_active) VALUES (?)',[$flag]),'42804');
            }
            foreach([true,false] as $emulate){
                // Native unnamed parameters remain compatible with transaction poolers.
                if($disable!==null)$pdo->setAttribute(\PDO::PGSQL_ATTR_DISABLE_PREPARES,true);
                $pdo->setAttribute(\PDO::ATTR_EMULATE_PREPARES,$emulate);
                $a=BooleanProbe::create(['is_active'=>true]);$b=BooleanProbe::create(['is_active'=>false]);
                $this->assertTrue($a->fresh()->is_active);$this->assertFalse($b->fresh()->is_active);
                $this->assertSame(1,BooleanProbe::where('is_active',true)->count());$this->assertSame(1,BooleanProbe::where('is_active',false)->count());
                $a->update(['is_active'=>false]);$b->update(['is_active'=>true]);
                $this->assertFalse($a->fresh()->is_active);$this->assertTrue($b->fresh()->is_active);
                $this->assertSame(1,BooleanProbe::where('is_active',false)->update(['is_active'=>true]));
                $this->assertSame(2,BooleanProbe::where('is_active',true)->delete());$this->assertSame(0,BooleanProbe::count());
                $named=$this->pg->selectOne('SELECT CAST(:yes AS boolean) AS yes, CAST(:no AS boolean) AS no',['yes'=>true,'no'=>false]);
                $this->assertTrue($named->yes);$this->assertFalse($named->no);
            }
        }catch(\PHPUnit\Framework\AssertionFailedError $e){throw $e;}
        catch(\Throwable $e){$this->fail('PostgreSQL CRUD failed; details redacted ('.get_class($e).', code '.$e->getCode().').');}
        finally {$pdo->setAttribute(\PDO::ATTR_EMULATE_PREPARES,$mode);if($disable!==null)$pdo->setAttribute(\PDO::PGSQL_ATTR_DISABLE_PREPARES,$disable);}
    }
    private function temporaryApplicationTables():void
    {
        $schema=$this->pg->selectOne('select nspname from pg_namespace where oid=pg_my_temp_schema()')->nspname;
        if(!preg_match('/^pg_temp_\d+$/',$schema))throw new \RuntimeException('Temporary namespace not available.');
        $this->pg->statement('SET LOCAL search_path TO "'.$schema.'"');
        $tables=[];
        foreach(glob(database_path('migrations/*.php')) as $file){
            preg_match_all('/Schema::create\s*\(\s*[\'\"]([a-z_][a-z0-9_]*)[\'\"]/i',file_get_contents($file),$matches);$tables=array_merge($tables,$matches[1]);
        }
        foreach(array_unique($tables) as $table){
            $columns=$this->pg->select('select column_name,data_type,column_default from information_schema.columns where table_schema = ? and table_name = ?',['public',$table]);
            if(!$columns)throw new \RuntimeException('Required application table is missing.');
            foreach($columns as $column)if(str_starts_with($column->column_default??'','nextval(')&&$column->column_name!=='id')throw new \RuntimeException('Unexpected serial default; refusing test writes.');
            $this->pg->statement('CREATE TEMP TABLE "'.$table.'" (LIKE public."'.$table.'" INCLUDING DEFAULTS) ON COMMIT DROP');
            foreach($columns as $column)if($column->column_name==='id'&&in_array($column->data_type,['bigint','integer','smallint'],true)){
                // Never advance a production sequence inherited by LIKE DEFAULTS.
                $this->pg->statement('ALTER TABLE pg_temp."'.$table.'" ALTER COLUMN id DROP DEFAULT');
                $this->pg->statement('ALTER TABLE pg_temp."'.$table.'" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
            }
            $this->assertSame($schema,$this->pg->selectOne('select n.nspname from pg_class c join pg_namespace n on c.relnamespace=n.oid where c.oid=to_regclass(?)',[$table])->nspname);
        }
    }
